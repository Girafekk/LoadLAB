def publish_demo_lesson(session: Session) -> int:
    """Публикует курс и первый урок, наполняя его блоками.

    Идемпотентно: если в уроке уже есть блоки, функция ничего не меняет и
    возвращает 0. Благодаря этому повторный запуск не перезаписывает контент
    и не публикует заново урок, который позже сняли с публикации.
    """
    course = session.scalar(select(Course).where(Course.slug == COURSE.slug))
    if course is None:
        raise RuntimeError("Сначала загрузите структуру курса: python -m app.db.seed")

    lesson = session.scalar(select(Lesson).where(Lesson.content_key == "w1-l1"))
    if lesson is None:
        raise RuntimeError("В курсе нет демо-урока w1-l1: проверьте структуру программы")

    # Считаем блоки запросом, а не через relationship: так повторный вызов
    # в той же ORM-сессии не добавит второй комплект блоков.
    blocks_exist = session.scalar(
        select(func.count()).select_from(LessonBlock).where(LessonBlock.lesson_id == lesson.id)
    )
    if blocks_exist:
        return 0

    course.is_published = True
    lesson.is_published = True

    for position, (block_type, content) in enumerate(DEMO_LESSON_BLOCKS, start=1):
        session.add(
            LessonBlock(
                lesson_id=lesson.id,
                type=block_type,
                content=content,
                position=position,
            )
        )
    session.flush()
    return len(DEMO_LESSON_BLOCKS)
