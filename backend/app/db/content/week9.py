def _spread_correct_positions(lessons):
    """Верный ответ не должен всегда стоять первым."""
    for lesson_data in lessons:
        for index, item in enumerate(lesson_data["questions"]):
            options = list(item["options"])
            shift = index % len(options)
            item["options"] = tuple(options[shift:] + options[:shift])
    return lessons


LESSONS = _spread_correct_positions(LESSONS)
