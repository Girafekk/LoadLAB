def publish_demo_quiz(session: Session) -> int:
    """Создаёт и публикует квиз первого урока. Идемпотентно, возвращает число вопросов."""
    course = session.scalar(select(Course).where(Course.slug == COURSE.slug))
    if course is None:
        raise RuntimeError("Сначала загрузите структуру курса: python -m app.db.seed")

    lesson = session.scalar(select(Lesson).where(Lesson.content_key == "w1-l1"))
    if lesson is None:
        raise RuntimeError("В курсе нет демо-урока w1-l1: проверьте структуру программы")

    existing = session.scalar(
        select(func.count()).select_from(Quiz).where(Quiz.lesson_id == lesson.id)
    )
    if existing:
        return 0

    quiz = Quiz(
        lesson_id=lesson.id,
        title=DEMO_QUIZ_TITLE,
        description="10 вопросов по теме урока с объяснением каждого ответа.",
        is_published=True,
    )
    session.add(quiz)
    session.flush()

    for position, question_data in enumerate(DEMO_QUIZ_QUESTIONS, start=1):
        question = QuizQuestion(
            quiz_id=quiz.id,
            kind=str(question_data["kind"]),
            text=str(question_data["text"]),
            explanation=str(question_data["explanation"]),
            position=position,
        )
        session.add(question)
        session.flush()
        for option_position, (option_text, is_correct) in enumerate(
            question_data["options"], start=1
        ):
            session.add(
                QuizOption(
                    question_id=question.id,
                    text=str(option_text),
                    is_correct=bool(is_correct),
                    position=option_position,
                )
            )
    session.flush()
    return len(DEMO_QUIZ_QUESTIONS)
